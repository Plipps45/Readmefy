let lang = "en";
try {
  const saved = localStorage.getItem("pf:lang");
  if (saved && LANGS[saved]) lang = saved;
} catch {}

export const getLang = () => lang;

export function setLang(l) {
  if (!LANGS[l]) return;
  lang = l;
  try {
    localStorage.setItem("pf:lang", l);
  } catch {}
}

// t("Hello {name}", { name }) in the editor language; README default texts fall back to render/lang.js
export function t(s, vars) {
  if (typeof s !== "string") return s;
  let out = DICT[lang]?.get(s) ?? tr(lang, s);
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return out;
}

// Static markup: [data-i18n] text, [data-i18n-html] markup, [data-i18n-attr="title,aria-label"] attributes.
// The English original is kept on the element so switching back and forth always starts from it.
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-i18n]")) {
    el.dataset.src ??= el.textContent.trim();
    el.textContent = t(el.dataset.src);
  }
  for (const el of root.querySelectorAll("[data-i18n-html]")) {
    el.dataset.src ??= el.innerHTML.trim();
    el.innerHTML = t(el.dataset.src);
  }
  for (const el of root.querySelectorAll("[data-i18n-attr]")) {
    for (const a of el.dataset.i18nAttr.split(",")) {
      const k = `src${a.replace(/(^|-)(\w)/g, (m, d, c) => c.toUpperCase())}`;
      el.dataset[k] ??= el.getAttribute(a) ?? "";
      el.setAttribute(a, t(el.dataset[k]));
    }
  }
}
